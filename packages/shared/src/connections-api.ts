import { z } from "zod";

/**
 * M63: the rest of the connections Storm itself uses, set up in Settings instead of .env (docs/design.md §7): the
 * Storm bot (Settings → Telegram) and Google's OAuth client (Settings → Google). Like the model servers (M62), their
 * secrets are sealed and write-only, and saving one asks for the authenticator code again.
 */

/** The authenticator code, asked again for a change that decides where your data goes (M62-T6). */
const Code = z.string().regex(/^\d{6}$/, "the 6-digit code from your authenticator app");

export const TELEGRAM_BOT_TOKEN_PATTERN = /^\d+:[\w-]{30,}$/;
export const TELEGRAM_WEBHOOK_SECRET_PATTERN = /^[A-Za-z0-9_-]{32,256}$/;

/**
 * Saving the Storm bot. The first save needs `botToken` and `chatId`; later ones change only what they name.
 * `webhook`: the secret Telegram sends with each update, pasted (your gateway's), or generated by Storm and shown once;
 * Storm keeps only its hash. `register` calls Telegram's setWebhook with it, at that address.
 */
export const TelegramConnectionSchema = z
  .object({
    botToken: z.string().trim().regex(TELEGRAM_BOT_TOKEN_PATTERN, "a bot token from @BotFather (123456:ABC...)").optional(),
    /** Your Telegram user id: your private chat with the bot. Messages go there only; commands are taken only from it. */
    chatId: z.string().trim().regex(/^-?\d{1,20}$/, "a numeric chat id").optional(),
    enabled: z.boolean().optional(),
    webhook: z
      .discriminatedUnion("secret", [
        z.object({ secret: z.literal("generate") }).strict(),
        z.object({ secret: z.literal("paste"), value: z.string().trim().regex(TELEGRAM_WEBHOOK_SECRET_PATTERN, "32 to 256 of A-Z a-z 0-9 _ -") }).strict(),
      ])
      .optional(),
    /** With `webhook`: register it with Telegram at this address (https; Telegram posts the updates there). */
    register: z.url({ protocol: /^https$/ }).max(500).optional(),
    code: Code.optional(),
  })
  .strict()
  .refine((body) => body.register === undefined || body.webhook !== undefined, {
    path: ["register"],
    message: "registering needs the webhook secret: paste it or generate one",
  });
export type TelegramConnectionRequest = z.infer<typeof TelegramConnectionSchema>;

export interface TelegramConnectionView {
  /** A bot token and a chat id are saved. */
  configured: boolean;
  enabled: boolean;
  chatId: string | null;
  /** The token's last four characters; the token itself is never returned. */
  tokenHint: string | null;
  /** A webhook secret is saved: /hooks/telegram takes updates that carry it. */
  webhookSecretSet: boolean;
  /** Where the webhook was last registered from Storm. */
  webhookUrl: string | null;
  dateUpdated: string | null;
}

/** The answer to a save: the generated webhook secret, this once, and how the registering went. */
export interface TelegramConnectionSaved extends TelegramConnectionView {
  webhookSecret?: string;
  registered?: { ok: boolean; error: string | null };
}

export interface TelegramTestView {
  ok: boolean;
  /** The bot's @username, when the token works. */
  bot: string | null;
  error: string | null;
}

/** Google's OAuth client (a Web application client of your Google Cloud project). */
export const GoogleClientSchema = z
  .object({
    clientId: z.string().trim().regex(/^[\w.-]+\.apps\.googleusercontent\.com$/, "…apps.googleusercontent.com"),
    /** Needed the first time; left out, the saved one stays. */
    clientSecret: z.string().trim().min(10).max(200).optional(),
    code: Code,
  })
  .strict();
export type GoogleClientRequest = z.infer<typeof GoogleClientSchema>;

export interface GoogleClientView {
  configured: boolean;
  clientId: string | null;
  secretHint: string | null;
}

